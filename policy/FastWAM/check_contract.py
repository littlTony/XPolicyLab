from pathlib import Path
from collections import Counter
import argparse
import hashlib
import json
import re
import numpy as np
from hydra import compose,initialize_config_dir
from fastwam.datasets.dexbench_contract import CONTRACT,DEFAULT_PROMPT
from fastwam.datasets.dexbench import DexBenchIndex

P=Path(__file__).resolve().parent


def validate_numeric_binding(stats,episode_ids,rows,numeric_sha256):
    """Detect stale numerical assets even when episode/frame counts agree."""
    provenance=stats.get('stats_provenance',{})
    if stats.get('train_rows')!=rows or stats.get('train_episodes')!=len(episode_ids):
        raise ValueError('FastWAM statistics describe another training population; run process_data.sh before training')
    if provenance.get('training_episode_ids')!=list(episode_ids):
        raise ValueError('FastWAM statistics use another training episode split; run process_data.sh')
    if provenance.get('train_numeric_sha256')!=numeric_sha256:
        raise ValueError('FastWAM source numeric values changed despite matching counts; run process_data.sh to regenerate statistics')
    if provenance.get('action_horizon')!=32 or provenance.get('variance_correction')!=1:
        raise ValueError('FastWAM statistics do not use the native forward32/sample-variance recipe')


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--require-text-cache',action='store_true');args=parser.parse_args()
    with initialize_config_dir(config_dir=str(P/'FastWAM/configs'),version_base='1.3'):
        cfg=compose(config_name='train',overrides=['task=dexbench_ee58'])
    from omegaconf import OmegaConf
    assert OmegaConf.to_container(cfg.action_contract)==CONTRACT
    assert cfg.model.proprio_dim==cfg.model.action_dit_config.action_dim==cfg.model.video_dit_config.action_dim==58
    stats=json.loads((P/'data/dataset_stats.json').read_text())
    assert stats['action_contract']==CONTRACT
    for section in ['action','state']:
        fields=stats[section]['default']
        assert all(np.asarray(fields[f'global_{k}']).shape==(58,) for k in ['mean','std','min','max'])
        for name,value in fields.items():
            assert np.isfinite(np.asarray(value)).all(),(section,name)
            if name.startswith('stepwise_'):
                assert np.asarray(value).shape==(32 if section=='action' else 1,58)
    from prepare_stats import load_training_episodes,METHOD
    if stats.get('stats_provenance',{}).get('method')!=METHOD:
        raise ValueError('FastWAM statistics are not generated by the native episode-equal reducer')
    train=DexBenchIndex(cfg.data.train.dataset_dirs[0],'train')
    val=DexBenchIndex(cfg.data.val.dataset_dirs[0],'val')
    info=json.loads((Path(cfg.data.train.dataset_dirs[0])/'meta/info.json').read_text())
    assert len(train)+len(val)==info['total_frames']
    assert not set(train.episodes.episode_index)&set(val.episodes.episode_index)
    if stats.get('train_rows')!=len(train):
        raise ValueError(f'Stale FastWAM statistics: saved training rows={stats.get("train_rows")}, current={len(train)}; run process_data.sh')
    # Hash physical EE58 values and the exact train episode split, not only
    # file counts. This is O(rows), with no image decoding or stats reduction.
    episodes,episode_ids,numeric_sha256=load_training_episodes(Path(cfg.data.train.dataset_dirs[0]))
    del episodes
    validate_numeric_binding(stats,episode_ids,len(train),numeric_sha256)
    assert Path(cfg.model.action_dit_pretrained_path).is_file()
    missing=[]
    prompts=set(str(row['tasks'][0]) for _,row in train.episodes.iterrows())|set(str(row['tasks'][0]) for _,row in val.episodes.iterrows())
    for text in prompts:
        h=hashlib.sha256(DEFAULT_PROMPT.format(task=text).encode()).hexdigest()
        f=Path(cfg.data.train.text_embedding_cache_dir)/f'{h}.t5_len128.wan22ti2v5b.pt'
        if not f.is_file():missing.append((text,str(f)))
    print(f'Verified absolute EE58: train {len(train.episodes)} episodes/{len(train)} rows; val {len(val.episodes)} episodes/{len(val)} rows')
    print(f'Verified current numeric statistics binding: {numeric_sha256}')
    print(f'Text cache: {len(prompts)-len(missing)}/{len(prompts)} prompts present')
    if missing:
        by_embodiment=Counter((re.match(r'^\[([^/]+)/',text).group(1) if re.match(r'^\[([^/]+)/',text) else 'unprefixed') for text,_ in missing)
        print('Missing text cache by embodiment:',dict(by_embodiment))
    if args.require_text_cache and missing:
        raise FileNotFoundError(f'Run process_data.sh --text-cache separately; missing {len(missing)} cached prompts, first={missing[0][1]}')


if __name__=='__main__':main()
